import { createLogger } from "@orkestra/config";
import type { SandboxRunRequest, SandboxRunResult } from "@orkestra/contracts";
import Docker from "dockerode";
import { randomUUID } from "node:crypto";
import path from "node:path";
import { PassThrough } from "node:stream";
import { CapacityPool, type ReleaseFn } from "./capacity-pool.js";
import { formatCommitMessage } from "./commit-attribution.js";

const log = createLogger("sandbox.manager");

const MAX_CONTAINER_TTL_MS = 60 * 60 * 1000; // 1 hour
const DEFAULT_STEP_TIMEOUT_MS = 20 * 60 * 1000;
const TAIL_BYTES = 8 * 1024;

export interface SandboxManagerOptions {
  docker?: Docker;
  pool?: CapacityPool;
  /** If provided, set as git author for commits made inside the sandbox. */
  committerName?: string;
  committerEmail?: string;
  /** Optional override: full remote push ref (e.g. `refs/heads/ai/...`). */
  pushRefOverride?: string;
  /** Attach AI attribution prefix + co-author on auto-commit. */
  aiAuthored?: boolean;
  /** The Jira ticket key to include as Refs: trailer on the commit. */
  ticketKey?: string;
  /** Commit subject/body generated by the developer agent. */
  commitMessage?: string;
}

type StepName = "install" | "lint" | "build" | "test_unit" | "test_integration";

interface StepResult {
  name: string;
  command: string;
  exitCode: number;
  durationMs: number;
  stdoutTail: string;
  stderrTail: string;
}

/**
 * Ring-buffer style tail accumulator: keeps last N bytes.
 */
class TailBuf {
  private chunks: Buffer[] = [];
  private size = 0;
  constructor(private readonly limit: number) {}
  push(b: Buffer) {
    this.chunks.push(b);
    this.size += b.length;
    while (this.size > this.limit && this.chunks.length > 1) {
      const drop = this.chunks.shift()!;
      this.size -= drop.length;
    }
  }
  toString(): string {
    const merged = Buffer.concat(this.chunks);
    const start = Math.max(0, merged.length - this.limit);
    return merged.slice(start).toString("utf8");
  }
}

/**
 * Check Docker socket availability on startup. Logs a warning (does not
 * throw) so tests and dev-mode paths without Docker can still import
 * this module.
 */
async function probeDocker(docker: Docker): Promise<boolean> {
  try {
    await docker.ping();
    return true;
  } catch (e) {
    log.warn({ err: e }, "Docker socket not reachable; sandbox runs will fail");
    return false;
  }
}

export class SandboxManager {
  private readonly docker: Docker;
  private readonly pool: CapacityPool;
  private readonly opts: SandboxManagerOptions;
  private readonly dockerReady: Promise<boolean>;

  constructor(opts: SandboxManagerOptions = {}) {
    this.docker = opts.docker ?? new Docker();
    this.pool = opts.pool ?? new CapacityPool();
    this.opts = opts;
    this.dockerReady = probeDocker(this.docker);
  }

  /**
   * Main entry point. Runs the full developer pipeline end-to-end.
   * Always releases the capacity slot and removes the ephemeral container.
   */
  async run(req: SandboxRunRequest): Promise<SandboxRunResult> {
    const correlationId = randomUUID();
    const l = log.child({ correlationId, workflowRunId: req.workflowRunId, repoUrl: req.repoUrl });

    await this.dockerReady;

    let release: ReleaseFn | undefined;
    let container: Docker.Container | undefined;
    const steps: StepResult[] = [];
    let coveragePct: number | null = null;
    let success = false;
    let commitSha: string | undefined;

    const ttlTimer = setTimeout(() => {
      l.warn({ ttlMs: MAX_CONTAINER_TTL_MS }, "container TTL reached; killing");
      container?.kill().catch(() => {});
    }, MAX_CONTAINER_TTL_MS);

    try {
      l.info("acquiring capacity slot");
      release = await this.pool.acquire();

      container = await this.createContainer(req, correlationId);

      // Network constraint: bridge (no host). We do not attach a host
      // network; an allow-list proxy belongs to deploy/infra.
      l.info("network constraint: bridge-only, no host network");

      await container.start();

      // Clone + checkout + branch.
      await this.execStep(
        container,
        "git-clone",
        [
          "sh",
          "-lc",
          `set -e && git clone --depth ${req.orkestra.clone_depth} ${shquote(req.repoUrl)} /workspace/repo && cd /workspace/repo && git fetch --depth ${req.orkestra.clone_depth} origin ${shquote(req.baseCommit)} && git checkout ${shquote(req.baseCommit)} && git checkout -b ${shquote(req.branchName)}`,
        ],
        steps,
        correlationId,
      );

      if (req.patch) {
        await this.writeFile(container, "/workspace/patch.diff", req.patch);
        await this.execStep(
          container,
          "git-apply",
          [
            "sh",
            "-lc",
            "cd /workspace/repo && git apply --whitespace=nowarn /workspace/patch.diff",
          ],
          steps,
          correlationId,
        );
      }

      if (req.orkestra.test_dependencies.length > 0) {
        // Sibling-container pattern: dependency containers are expected to
        // be launched through the docker socket by the caller (infra-level
        // orchestration). We only log the constraint here so the runtime
        // contract is explicit.
        l.info(
          { deps: req.orkestra.test_dependencies },
          "test_dependencies declared; expect sibling containers on ephemeral network",
        );
      }

      const orderedSteps: Array<{ name: StepName; cmd?: string }> = [
        { name: "install", cmd: req.orkestra.commands.install },
        { name: "lint", cmd: req.orkestra.commands.lint },
        { name: "build", cmd: req.orkestra.commands.build },
        { name: "test_unit", cmd: req.orkestra.commands.test_unit },
        { name: "test_integration", cmd: req.orkestra.commands.test_integration },
      ];

      for (const s of orderedSteps) {
        if (!s.cmd) continue;
        const r = await this.execStep(
          container,
          s.name,
          ["sh", "-lc", `cd /workspace/repo && ${s.cmd}`],
          steps,
          correlationId,
        );
        if (r.exitCode !== 0) {
          l.warn({ step: s.name, exit: r.exitCode }, "step failed; aborting pipeline");
          break;
        }
      }

      coveragePct = this.parseCoverage(steps);
      success = steps.length > 0 && steps.every((s) => s.exitCode === 0);

      if (success) {
        commitSha = await this.commitAndPush(container, req, correlationId);
      }

      return {
        success,
        steps,
        coveragePct,
        commitSha,
      };
    } catch (e) {
      l.error({ err: e }, "sandbox run failed");
      return {
        success: false,
        steps,
        coveragePct,
        commitSha,
      };
    } finally {
      clearTimeout(ttlTimer);
      if (container) {
        try {
          await container.stop({ t: 5 }).catch(() => {});
          await container.remove({ force: true, v: true }).catch(() => {});
        } catch (e) {
          l.warn({ err: e }, "cleanup failed");
        }
      }
      if (release) {
        try {
          await release();
        } catch (e) {
          l.warn({ err: e }, "capacity release failed");
        }
      }
    }
  }

  // --------------------------------------------------------------------- //
  //  Helpers
  // --------------------------------------------------------------------- //

  private async createContainer(
    req: SandboxRunRequest,
    correlationId: string,
  ): Promise<Docker.Container> {
    const l = log.child({ correlationId });
    const envList = [
      ...Object.entries(req.secrets).map(([k, v]) => `${k}=${v}`),
      "CI=true",
      "ORKESTRA_SANDBOX=1",
    ];

    // Pull image if missing.
    try {
      await this.docker.getImage(req.orkestra.sandbox_image).inspect();
    } catch {
      l.info({ image: req.orkestra.sandbox_image }, "pulling sandbox image");
      await new Promise<void>((resolve, reject) => {
        this.docker.pull(
          req.orkestra.sandbox_image,
          (err: Error | null, stream: NodeJS.ReadableStream) => {
            if (err) return reject(err);
            this.docker.modem.followProgress(stream, (e) => (e ? reject(e) : resolve()));
          },
        );
      });
    }

    const container = (await this.docker.createContainer({
      Image: req.orkestra.sandbox_image,
      Cmd: ["sh", "-lc", "mkdir -p /workspace && exec sleep 3600"],
      Tty: false,
      Env: envList,
      User: "1000:1000",
      WorkingDir: "/workspace",
      Labels: {
        "orkestra.role": "sandbox",
        "orkestra.workflowRunId": req.workflowRunId,
        "orkestra.correlationId": correlationId,
      },
      HostConfig: {
        AutoRemove: false,
        NetworkMode: "bridge",
        ReadonlyRootfs: true,
        SecurityOpt: ["no-new-privileges"],
        Tmpfs: {
          "/tmp": "rw,exec,nosuid,size=512m",
        },
        Mounts: [
          {
            Type: "tmpfs",
            Source: "",
            Target: "/workspace",
            TmpfsOptions: { SizeBytes: 2 * 1024 * 1024 * 1024, Mode: 0o1777 },
          },
        ],
        CapDrop: ["ALL"],
      },
    })) as Docker.Container;

    l.info(
      { image: req.orkestra.sandbox_image, id: (container as unknown as { id: string }).id },
      "container created",
    );
    return container;
  }

  private async execStep(
    container: Docker.Container,
    name: string,
    cmd: string[],
    steps: StepResult[],
    correlationId: string,
    timeoutMs = DEFAULT_STEP_TIMEOUT_MS,
  ): Promise<StepResult> {
    const l = log.child({ correlationId, step: name });
    const start = Date.now();

    const exec = await container.exec({
      Cmd: cmd,
      AttachStdout: true,
      AttachStderr: true,
      User: "1000:1000",
    });

    const stdout = new TailBuf(TAIL_BYTES);
    const stderr = new TailBuf(TAIL_BYTES);
    const outStream = new PassThrough();
    const errStream = new PassThrough();
    outStream.on("data", (c) => stdout.push(Buffer.from(c)));
    errStream.on("data", (c) => stderr.push(Buffer.from(c)));

    const stream = await exec.start({ hijack: true, stdin: false });
    this.docker.modem.demuxStream(stream, outStream, errStream);

    let timedOut = false;
    const timer = setTimeout(async () => {
      timedOut = true;
      l.warn({ timeoutMs }, "step timeout; aborting");
      try {
        (stream as NodeJS.ReadableStream).pause();
      } catch {
        /* noop */
      }
    }, timeoutMs);

    await new Promise<void>((resolve) => {
      stream.on("end", () => resolve());
      stream.on("close", () => resolve());
      stream.on("error", () => resolve());
    });
    clearTimeout(timer);

    const inspect = await exec.inspect();
    const exitCode = timedOut ? 124 : (inspect.ExitCode ?? -1);
    const durationMs = Date.now() - start;

    const r: StepResult = {
      name,
      command: cmd.slice(-1)[0] ?? cmd.join(" "),
      exitCode,
      durationMs,
      stdoutTail: stdout.toString(),
      stderrTail: stderr.toString(),
    };
    steps.push(r);
    l.info({ exit: exitCode, durationMs }, "step done");
    return r;
  }

  private async writeFile(
    container: Docker.Container,
    target: string,
    content: string,
  ): Promise<void> {
    // Use a heredoc via /tmp to avoid tar roundtripping for small files.
    const b64 = Buffer.from(content, "utf8").toString("base64");
    const dir = path.posix.dirname(target);
    const exec = await container.exec({
      Cmd: [
        "sh",
        "-lc",
        `mkdir -p ${shquote(dir)} && echo ${shquote(b64)} | base64 -d > ${shquote(target)}`,
      ],
      AttachStdout: true,
      AttachStderr: true,
    });
    const stream = await exec.start({ hijack: true, stdin: false });
    await new Promise<void>((resolve) => {
      stream.on("end", () => resolve());
      stream.on("close", () => resolve());
    });
    const info = await exec.inspect();
    if (info.ExitCode !== 0) throw new Error(`writeFile ${target} failed (exit ${info.ExitCode})`);
  }

  private parseCoverage(steps: StepResult[]): number | null {
    for (const s of steps) {
      const blob = `${s.stdoutTail}\n${s.stderrTail}`;
      const m = blob.match(/(?:All files|TOTAL|total coverage)[^\n]*?(\d{1,3}(?:\.\d+)?)\s*%/i);
      if (m) {
        const n = parseFloat(m[1]!);
        if (!Number.isNaN(n) && n >= 0 && n <= 100) return n;
      }
    }
    return null;
  }

  private async commitAndPush(
    container: Docker.Container,
    req: SandboxRunRequest,
    correlationId: string,
  ): Promise<string | undefined> {
    const l = log.child({ correlationId });
    const ai = this.opts.aiAuthored ?? true;
    const ticket = this.opts.ticketKey ?? req.branchName;
    const subject = this.opts.commitMessage ?? `update ${req.branchName}`;
    const message = formatCommitMessage(ticket, ai, subject);
    const name = this.opts.committerName ?? "Orkestra Bot";
    const email = this.opts.committerEmail ?? "orkestra@users.noreply";
    const pushRef = this.opts.pushRefOverride ?? req.branchName;

    await this.writeFile(container, "/workspace/commit.msg", message);

    const steps: StepResult[] = [];
    const commitRes = await this.execStep(
      container,
      "git-commit",
      [
        "sh",
        "-lc",
        `cd /workspace/repo && git add -A && git -c user.email=${shquote(email)} -c user.name=${shquote(name)} commit -F /workspace/commit.msg`,
      ],
      steps,
      correlationId,
    );
    if (commitRes.exitCode !== 0) {
      l.warn({ tail: commitRes.stderrTail }, "commit failed");
      return undefined;
    }

    const shaRes = await this.execStep(
      container,
      "git-rev-parse",
      ["sh", "-lc", "cd /workspace/repo && git rev-parse HEAD"],
      steps,
      correlationId,
    );
    const sha = shaRes.stdoutTail.trim();

    const pushRes = await this.execStep(
      container,
      "git-push",
      ["sh", "-lc", `cd /workspace/repo && git push origin HEAD:${shquote(pushRef)}`],
      steps,
      correlationId,
    );
    if (pushRes.exitCode !== 0) {
      l.warn({ tail: pushRes.stderrTail }, "push failed");
      return sha || undefined;
    }

    l.info({ sha, pushRef }, "commit pushed");
    return sha || undefined;
  }
}

/** Minimal single-arg shell quoter. Wraps in single-quotes, escapes embedded '. */
function shquote(s: string): string {
  return `'${String(s).replace(/'/g, "'\\''")}'`;
}
